#!/usr/bin/env -S python3 -I
"""Keeps the translations in step with the code.

  scripts/strings.py extract   writes every L("...") key in Sources/ to Resources/Localization/en.lproj/Localizable.strings
  scripts/strings.py prune     removes keys the code no longer uses from every language
  scripts/strings.py check     fails if any language misses a key, has an unknown one, or changes a key's placeholders

Keys are the English text. Placeholders are %@ or numbered %1$@, %2$@; a translation must use
exactly the same set, in any order.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "Sources"
LOCALIZATION = ROOT / "Resources" / "Localization"
KEY_PATTERN = re.compile(r'\bL\("((?:[^"\\]|\\.)*)"')
ENTRY_PATTERN = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;\s*$')
PLACEHOLDER_PATTERN = re.compile(r"%(?:\d+\$)?@")


def source_keys():
    keys = set()
    for path in sorted(SOURCES.rglob("*.swift")):
        if path.name == "main.swift":
            continue
        keys.update(KEY_PATTERN.findall(path.read_text(encoding="utf-8")))
    return keys


def placeholders(text):
    found = PLACEHOLDER_PATTERN.findall(text)
    # A single unnumbered %@ and a single %1$@ mean the same thing.
    normalized = ["%1$@" if item == "%@" and len(found) == 1 else item for item in found]
    return sorted(normalized)


def read_strings(path):
    entries = {}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        stripped = line.strip()
        if not stripped or stripped.startswith("/*") or stripped.startswith("//"):
            continue
        match = ENTRY_PATTERN.match(line)
        if not match:
            raise SystemExit(f"{path.relative_to(ROOT)}:{number}: cannot parse line: {line}")
        entries[match.group(1)] = match.group(2)
    return entries


def extract():
    target = LOCALIZATION / "en.lproj" / "Localizable.strings"
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = ["/* Source strings. Generated by scripts/strings.py extract; do not edit by hand. */", ""]
    lines += [f'"{key}" = "{key}";' for key in sorted(source_keys())]
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines) - 2} keys -> {target.relative_to(ROOT)}")


def prune():
    keys = source_keys()
    for folder in sorted(LOCALIZATION.glob("*.lproj")):
        path = folder / "Localizable.strings"
        lines = path.read_text(encoding="utf-8").splitlines()
        kept = [line for line in lines if not (ENTRY_PATTERN.match(line) and ENTRY_PATTERN.match(line).group(1) not in keys)]
        if len(kept) != len(lines):
            path.write_text("\n".join(kept) + "\n", encoding="utf-8")
            print(f"{folder.stem}: removed {len(lines) - len(kept)}")


def check():
    keys = source_keys()
    problems = []
    languages = sorted(LOCALIZATION.glob("*.lproj"))
    if not languages:
        raise SystemExit("no translations found; run scripts/strings.py extract first")
    for folder in languages:
        path = folder / "Localizable.strings"
        entries = read_strings(path)
        name = folder.stem
        for key in sorted(keys - entries.keys()):
            problems.append(f"{name}: missing {key!r}")
        for key in sorted(entries.keys() - keys):
            problems.append(f"{name}: unused {key!r}")
        for key in sorted(keys & entries.keys()):
            if placeholders(key) != placeholders(entries[key]):
                problems.append(f"{name}: placeholders differ for {key!r}: {entries[key]!r}")
    if problems:
        print("\n".join(problems))
        raise SystemExit(f"{len(problems)} problem(s) in translations")
    print(f"{len(keys)} keys, {len(languages)} languages: OK")


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "extract":
        extract()
    elif command == "prune":
        prune()
    elif command == "check":
        check()
    else:
        raise SystemExit(__doc__)
