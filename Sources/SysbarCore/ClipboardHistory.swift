import CryptoKit
import Foundation

/// What a copied item is kept as, by what it can be pasted back as.
public enum ClipboardKind: String, Codable, CaseIterable, Sendable {
    case text, link, richText, image, files

    private static let fileTypes: Set<String> = ["public.file-url", "NSFilenamesPboardType"]
    private static let imageTypes: Set<String> = ["public.png", "public.tiff", "public.jpeg"]
    private static let linkSchemes: Set<String> = ["http", "https", "ftp", "mailto"]

    /// What a pasteboard holding `types`, with `text` as its plain text, is kept as; nil when it
    /// holds nothing worth keeping. Files win over text (Finder also writes their names as text),
    /// and text over an image (a copied web page often carries both).
    public static func of(types: [String], text: String?) -> ClipboardKind? {
        let types = Set(types)
        if !types.isDisjoint(with: fileTypes) { return .files }
        let trimmed = text?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        if !trimmed.isEmpty {
            if isLink(trimmed) { return .link }
            return types.contains("public.rtf") ? .richText : .text
        }
        return types.isDisjoint(with: imageTypes) ? nil : .image
    }

    /// One web or mail address and nothing else.
    public static func isLink(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
              linkSchemes.contains(scheme) else { return false }
        if scheme == "mailto" { return !url.absoluteString.dropFirst("mailto:".count).isEmpty }
        return !(url.host ?? "").isEmpty
    }
}

/// Which kinds of copies the history shows. Rich text is text with formatting, which a user
/// does not tell apart from plain text, so both are under Text.
public enum ClipboardFilter: String, CaseIterable, Sendable {
    case all, text, link, image, files

    public func includes(_ kind: ClipboardKind) -> Bool {
        switch self {
        case .all: true
        case .text: kind == .text || kind == .richText
        case .link: kind == .link
        case .image: kind == .image
        case .files: kind == .files
        }
    }
}

/// One copied item. Text and file paths are kept here; an image or rich text sits in a file beside
/// the history, named after `id`.
public struct ClipboardEntry: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID
    public var kind: ClipboardKind
    /// The plain text: the text itself, the link, or rich text without its formatting.
    public var text: String
    public var paths: [String]
    /// The same content copied again has the same fingerprint, so it moves up instead of repeating.
    public var fingerprint: String
    /// The bundle identifier of the app it was copied in, when known.
    public var source: String?
    public var date: Date

    public init(
        id: UUID = UUID(), kind: ClipboardKind, text: String = "", paths: [String] = [],
        fingerprint: String, source: String? = nil, date: Date
    ) {
        self.id = id
        self.kind = kind
        self.text = text
        self.paths = paths
        self.fingerprint = fingerprint
        self.source = source
        self.date = date
    }

    /// The name of the file holding the image or rich text; nil for kinds kept in the entry.
    public var fileName: String? {
        switch kind {
        case .image: "\(id.uuidString).png"
        case .richText: "\(id.uuidString).rtf"
        case .text, .link, .files: nil
        }
    }

    /// Plain, rich and link copies of the same words share one fingerprint: the newest wins.
    public static func fingerprint(text: String) -> String { digest("text", Data(text.utf8)) }
    public static func fingerprint(paths: [String]) -> String { digest("files", Data(paths.joined(separator: "\0").utf8)) }
    public static func fingerprint(data: Data) -> String { digest("data", data) }

    private static func digest(_ prefix: String, _ content: Data) -> String {
        var hash = SHA256()
        hash.update(data: Data((prefix + "\0").utf8))
        hash.update(data: content)
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

/// Copies that ask not to be kept: passwords and one-time codes from password managers, and
/// content apps mark as short-lived. See nspasteboard.org.
public enum ClipboardPrivacy {
    public static let markerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// Apps whose copies are not kept until the user changes the list: they hold passwords.
    public static let defaultIgnoredApps = ["com.apple.keychainaccess", "com.apple.Passwords"]

    public static func isPrivate(types: [String]) -> Bool {
        !markerTypes.isDisjoint(with: types)
    }
}

/// The copied items, newest first.
public enum ClipboardHistory {
    /// How many items Settings offers to keep.
    public static let limits = [25, 50, 100, 200]
    public static let defaultLimit = 50
    /// Larger copies are not kept: a huge log or a raw photo would bloat the history on disk.
    public static let maxTextLength = 100_000
    /// Rich text that is larger is kept as plain text.
    public static let maxRichTextBytes = 20_000_000

    public static func normalizedLimit(_ value: Int?) -> Int {
        value.flatMap { limits.contains($0) ? $0 : nil } ?? defaultLimit
    }

    /// `entry` first. An older entry with the same content is replaced, unless `keepingDuplicates`, and
    /// the oldest beyond `limit` go; `dropped` lists both, so their files can be deleted.
    public static func adding(
        _ entry: ClipboardEntry, to list: [ClipboardEntry], limit: Int, keepingDuplicates: Bool = false
    ) -> (kept: [ClipboardEntry], dropped: [ClipboardEntry]) {
        let replaced = keepingDuplicates ? [] : list.filter { $0.fingerprint == entry.fingerprint }
        let rest = keepingDuplicates ? list : list.filter { $0.fingerprint != entry.fingerprint }
        let change = trimmed([entry] + rest, to: limit)
        return (change.kept, replaced + change.dropped)
    }

    /// The entries copied within `retention` of `now`; the older ones are `dropped`. An entry copied
    /// again from the history counts from that copy.
    public static func expired(
        _ list: [ClipboardEntry], keeping retention: ClipboardRetention, now: Date
    ) -> (kept: [ClipboardEntry], dropped: [ClipboardEntry]) {
        guard let seconds = retention.seconds else { return (list, []) }
        let cutoff = now.addingTimeInterval(-seconds)
        return (list.filter { $0.date >= cutoff }, list.filter { $0.date < cutoff })
    }

    public static func trimmed(_ list: [ClipboardEntry], to limit: Int) -> (kept: [ClipboardEntry], dropped: [ClipboardEntry]) {
        let count = max(0, limit)
        return (Array(list.prefix(count)), Array(list.dropFirst(count)))
    }

    /// The entry with `id` moves to the top, dated `date`: it was just copied again from the history.
    public static func promoting(_ id: UUID, in list: [ClipboardEntry], at date: Date) -> [ClipboardEntry] {
        guard let index = list.firstIndex(where: { $0.id == id }) else { return list }
        var entry = list[index]
        entry.date = date
        return [entry] + list.enumerated().filter { $0.offset != index }.map(\.element)
    }

    /// Entries whose text or file names contain `query`, ignoring case and accents. A blank query matches all.
    public static func matching(_ query: String, in list: [ClipboardEntry]) -> [ClipboardEntry] {
        let needle = folded(query.trimmingCharacters(in: .whitespacesAndNewlines))
        guard !needle.isEmpty else { return list }
        return list.filter { entry in
            let names = entry.paths.map { ($0 as NSString).lastPathComponent }
            return ([entry.text] + names).contains { folded($0).contains(needle) }
        }
    }

    /// `matching(_:in:)` among the entries `filter` includes.
    public static func matching(_ query: String, filter: ClipboardFilter, in list: [ClipboardEntry]) -> [ClipboardEntry] {
        matching(query, in: list.filter { filter.includes($0.kind) })
    }

    /// The filters worth offering: All, and each other filter that has an entry in `list`.
    public static func availableFilters(in list: [ClipboardEntry]) -> [ClipboardFilter] {
        ClipboardFilter.allCases.filter { filter in
            filter == .all || list.contains { filter.includes($0.kind) }
        }
    }

    /// The text on one line, with runs of whitespace as single spaces, cut at `maxLength` characters.
    public static func preview(of text: String, maxLength: Int = 80) -> String {
        let line = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return line.count > maxLength ? String(line.prefix(maxLength)) + "…" : line
    }

    private static func folded(_ text: String) -> String {
        text.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil)
    }
}

/// How long copies are kept. Counted from the last time an item was copied.
public enum ClipboardRetention: String, CaseIterable, Sendable {
    case day, week, month, quarter, forever

    /// Nil for `forever`.
    public var seconds: TimeInterval? {
        switch self {
        case .day: 86_400
        case .week: 7 * 86_400
        case .month: 30 * 86_400
        case .quarter: 90 * 86_400
        case .forever: nil
        }
    }

    public static func normalized(_ value: String?) -> ClipboardRetention {
        value.flatMap(ClipboardRetention.init(rawValue:)) ?? .forever
    }
}

/// Which kinds of copies are recorded.
public enum ClipboardRecording {
    /// Nothing stored means every kind. Names that are not kinds are ignored; a list with none that
    /// is valid counts as nothing stored.
    public static func normalized(stored: [String]?) -> Set<ClipboardKind> {
        guard let stored else { return Set(ClipboardKind.allCases) }
        let kinds = Set(stored.compactMap(ClipboardKind.init(rawValue:)))
        return kinds.isEmpty && !stored.isEmpty ? Set(ClipboardKind.allCases) : kinds
    }

    public static func stored(_ kinds: Set<ClipboardKind>) -> [String] {
        ClipboardKind.allCases.filter(kinds.contains).map(\.rawValue)
    }

    /// What a copy of `kind` is kept as, or nil when it is skipped. Rich text with its formatting left
    /// out is plain text, so turning rich text off still keeps the words.
    public static func kept(_ kind: ClipboardKind, allowed: Set<ClipboardKind>) -> ClipboardKind? {
        if allowed.contains(kind) { return kind }
        return kind == .richText && allowed.contains(.text) ? .text : nil
    }
}
